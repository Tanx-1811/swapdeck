import Foundation

public enum Language: String, Sendable {
    case en, vi

    /// The language to show for a preference ("auto" follows macOS).
    public static func resolve(_ preference: LanguagePreference, preferred: [String] = Locale.preferredLanguages) -> Language {
        switch preference {
        case .en: return .en
        case .vi: return .vi
        case .auto: return preferred.first?.lowercased().hasPrefix("vi") == true ? .vi : .en
        }
    }

    public var locale: Locale { Locale(identifier: self == .vi ? "vi_VN" : "en_US") }
}

/// UI text in English and Vietnamese. `{name}` placeholders are filled from `params`.
public struct Translator: Sendable {
    public let language: Language

    public init(_ language: Language) {
        self.language = language
    }

    public func callAsFunction(_ key: String, _ params: [String: String] = [:]) -> String {
        let template = (language == .vi ? Messages.vi[key] : nil) ?? Messages.en[key] ?? key
        return params.reduce(template) { text, param in text.replacingOccurrences(of: "{\(param.key)}", with: param.value) }
    }

    /// "3 pages" / "1 page".
    public func count(_ n: Int, one: String, many: String) -> String {
        n == 1 ? callAsFunction(one) : callAsFunction(many, ["n": String(n)])
    }

    public func relative(_ date: Date, now: Date = Date()) -> String {
        let formatter = RelativeDateTimeFormatter()
        formatter.locale = language.locale
        formatter.unitsStyle = .full
        return formatter.localizedString(for: date, relativeTo: now)
    }
}

